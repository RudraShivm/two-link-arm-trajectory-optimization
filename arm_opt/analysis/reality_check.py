"""Dynamic reality check: open-loop forward integration using high-order ODE solvers.

Tests whether the optimal control sequences tau*(t) generated by discrete
transcription methods actually satisfy the continuous equations of motion,
measuring integration drift and defect leakage.
"""

from dataclasses import dataclass
from typing import Callable, Optional, Tuple
import numpy as np
from scipy.interpolate import interp1d
from scipy.integrate import solve_ivp
from arm_opt.dynamics.kinematics import forward_kinematics
from arm_opt.solvers.base import TrajectoryProblem, TrajectoryResult


@dataclass
class RealityCheckResult:
    """Quantitative comparison between optimizer claims and true continuous physics.

    Attributes:
        t_sim: High-resolution continuous time grid.
        x_sim: Forward-simulated continuous state trajectory of shape (M, 4).
        x_opt_interp: Optimizer state trajectory interpolated onto t_sim.
        max_state_drift: Maximum Euclidean norm ||x_sim(t) - x_opt(t)|| over time.
        max_cartesian_drift: Maximum end-effector drift in meters over time.
        terminal_cartesian_drift: End-effector miss distance at T in meters.
    """

    t_sim: np.ndarray
    x_sim: np.ndarray
    x_opt_interp: np.ndarray
    max_state_drift: float
    max_cartesian_drift: float
    terminal_cartesian_drift: float


def perform_reality_check(
    problem: TrajectoryProblem,
    result: TrajectoryResult,
    num_eval_points: int = 200,
    state_interp_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
) -> RealityCheckResult:
    """Simulates the true continuous dynamics under the optimized control profile.

    Args:
        state_interp_fn: Optional t -> x(t) of shape (M, 4) used to place the
            optimizer's state between nodes. Default None keeps the old
            straight-line (linear) interpolation. Only max_state_drift and
            max_cartesian_drift depend on it; terminal_cartesian_drift does not.
    """
    t_opt = result.time
    u_opt = result.control
    x_opt = result.state
    arm = problem.arm
    params = problem.arm_params

    # Continuous control interpolator
    control_interpolator = interp1d(
        t_opt, u_opt, axis=0, kind="linear", fill_value="extrapolate"
    )

    def continuous_dynamics(t: float, x: np.ndarray) -> np.ndarray:
        u = control_interpolator(t)
        return arm.state_derivative(x, u)

    t_span = (0.0, float(problem.duration))
    t_eval = np.linspace(0.0, float(problem.duration), num_eval_points)

    # 8th-order Runge-Kutta Dormand-Prince integrator with tight tolerances
    sim_sol = solve_ivp(
        fun=continuous_dynamics,
        t_span=t_span,
        y0=problem.x0,
        method="DOP853",
        t_eval=t_eval,
        rtol=1e-8,
        atol=1e-8,
    )

    t_sim = sim_sol.t
    x_sim = sim_sol.y.T  # shape: (num_eval_points, 4)

    # Interpolate optimizer state onto simulation grid
    if state_interp_fn is None:
        state_interpolator = interp1d(t_opt, x_opt, axis=0, kind="linear")  # old behavior
        x_opt_interp = state_interpolator(t_sim)
    else:
        x_opt_interp = np.asarray(state_interp_fn(t_sim))

    # Calculate state drift
    state_diffs = np.linalg.norm(x_sim - x_opt_interp, axis=1)
    max_state_drift = float(np.max(state_diffs))

    # Calculate Cartesian end-effector drift
    ee_drifts = np.zeros(len(t_sim))
    for i in range(len(t_sim)):
        _, p_sim = forward_kinematics(x_sim[i, :2], params)
        _, p_opt = forward_kinematics(x_opt_interp[i, :2], params)
        ee_drifts[i] = np.linalg.norm(p_sim - p_opt)

    max_cartesian_drift = float(np.max(ee_drifts))

    _, p_sim_final = forward_kinematics(x_sim[-1, :2], params)
    _, p_target = forward_kinematics(problem.xf[:2], params)
    terminal_cartesian_drift = float(np.linalg.norm(p_sim_final - p_target))

    return RealityCheckResult(
        t_sim=t_sim,
        x_sim=x_sim,
        x_opt_interp=x_opt_interp,
        max_state_drift=max_state_drift,
        max_cartesian_drift=max_cartesian_drift,
        terminal_cartesian_drift=terminal_cartesian_drift,
    )

